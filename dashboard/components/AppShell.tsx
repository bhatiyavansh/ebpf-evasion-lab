"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

const NAV = [
  { href: "/", label: "← TraceWeaver" },
  { href: "/lab", label: "Experiment Lab" },
  { href: "/cve-lab", label: "CVE Lab" },
  { href: "/outcome", label: "Study Outcome" },
  { href: "/demo", label: "Demo" },
];

function LabMark() {
  return (
    <svg width="26" height="26" viewBox="0 0 26 26" fill="none" aria-hidden>
      <rect x="1" y="1" width="24" height="24" rx="6" stroke="#2dd4bf" strokeOpacity="0.5" />
      <circle cx="13" cy="13" r="3" fill="#2dd4bf" />
      <path d="M13 4v4M13 18v4M4 13h4M18 13h4" stroke="#2dd4bf" strokeWidth="1.4" strokeLinecap="round" />
      <circle cx="13" cy="13" r="7.5" stroke="#2dd4bf" strokeOpacity="0.3" />
    </svg>
  );
}

export default function AppShell({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();

  // The TraceWeaver product (/) and the demo route each own their full chrome —
  // render them without the legacy multi-route shell. The remaining routes
  // (/lab, /cve-lab, /outcome) are the preserved research archive and keep the
  // shell nav below.
  if (pathname === "/" || pathname === "/demo") return <>{children}</>;

  return (
    <div className="min-h-screen bg-surface">
      <header className="sticky top-0 z-30 border-b border-surface-border bg-surface/90 backdrop-blur">
        <div className="mx-auto flex max-w-[1360px] flex-wrap items-center gap-x-4 gap-y-2 px-4 py-3 sm:px-8">
          <Link href="/" className="flex items-center gap-2.5">
            <LabMark />
            <div>
              <div className="text-[13px] font-semibold tracking-tight text-ink">
                ADAPTIVE eBPF SECURITY LAB
              </div>
              <div className="text-[10px] text-ink-faint">
                Runtime observability &amp; detection evaluation for Linux containers
              </div>
            </div>
          </Link>
          <nav className="order-3 -mx-1 flex w-full items-center gap-1 overflow-x-auto sm:order-2 sm:mx-0 sm:w-auto sm:flex-1">
            {NAV.map((n) => {
              const active = n.href === "/" ? pathname === "/" : pathname.startsWith(n.href);
              return (
                <Link
                  key={n.href}
                  href={n.href}
                  className={`shrink-0 rounded-md px-3 py-1.5 text-[12px] font-medium transition ${
                    active
                      ? "bg-accent/15 text-accent"
                      : "text-ink-faint hover:bg-surface-hover hover:text-ink"
                  }`}
                >
                  {n.label}
                </Link>
              );
            })}
          </nav>
          <div className="order-2 ml-auto flex items-center gap-2 sm:order-3">
            <span className="hidden items-center gap-1.5 rounded-md border border-accent/25 bg-accent/5 px-2.5 py-1 text-[10px] font-medium uppercase tracking-wide text-accent md:inline-flex">
              Research prototype
            </span>
            <Link
              href="/demo"
              className="rounded-md border border-accent/40 bg-accent/10 px-3 py-1.5 text-[11px] font-semibold uppercase tracking-wide text-accent hover:bg-accent/20"
            >
              ▶ Demo
            </Link>
          </div>
        </div>
      </header>

      <main className="mx-auto max-w-[1360px] px-4 py-6 sm:px-8">{children}</main>

      <footer className="mx-auto max-w-[1360px] px-4 pb-8 pt-2 text-center text-[10.5px] text-ink-faint sm:px-8">
        Every status is generated by <span className="mono">scripts/normalize.py</span> from immutable{" "}
        <span className="mono">results/raw/*.json</span> evidence and verified by{" "}
        <span className="mono">scripts/validate.py</span>. Research prototype — findings are specific
        to the tested configurations.
      </footer>
    </div>
  );
}
