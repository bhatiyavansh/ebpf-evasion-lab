function Bar({
  segments,
  total,
}: {
  segments: { v: number; cls: string; label: string }[];
  total: number;
}) {
  return (
    <div className="flex h-3 w-full overflow-hidden rounded-full bg-surface-inset">
      {total === 0 ? (
        <div className="h-full w-full bg-surface-inset" />
      ) : (
        segments.map((s, i) =>
          s.v > 0 ? (
            <div key={i} className={`h-full ${s.cls}`} style={{ width: `${(s.v / total) * 100}%` }} title={`${s.label}: ${s.v}`} />
          ) : null
        )
      )}
    </div>
  );
}

